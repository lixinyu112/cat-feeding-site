const PRIORITY = {danger: 0, avoid: 1, surprise: 2, love: 3, okay: 4, curious: 5};
const ALIASES = FOOD_ENTRIES.flatMap(entry =>
  entry.aliases.map(alias => ({...entry, alias}))
);

function lookupItem(input) {
  const normalized = input.trim().toLowerCase().replace(/\s+/g, "");
  const exact = ALIASES.find(item => item.alias.toLowerCase() === normalized);
  if (exact) return exact;
  const partial = ALIASES.filter(item =>
    item.alias.length > 1 && normalized.includes(item.alias.toLowerCase())
  );
  partial.sort((a, b) => b.alias.length - a.alias.length || PRIORITY[a.category] - PRIORITY[b.category]);
  return partial[0] || {category: "unknown", emoji: "❔", alias: input};
}

if (typeof module !== "undefined") module.exports = {lookupItem};
